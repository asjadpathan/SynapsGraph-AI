import React, { useState, useEffect } from 'react';
import { Sparkles, BookOpen, AlertCircle, FileText } from 'lucide-react';
import { PaperService } from '../services/api';
import { useWorkspace } from '../context/WorkspaceContext';

export default function ResearchGapsView() {
  const { activeWorkspace } = useWorkspace();
  const [gapRes, setGapRes] = useState(null);
  const [loading, setLoading] = useState(true);
  const [errorMsg, setErrorMsg] = useState('');

  useEffect(() => {
    if (activeWorkspace?.project_id) {
      setLoading(true);
      setErrorMsg('');
      PaperService.detectResearchGaps(activeWorkspace.project_id)
        .then(res => {
          setGapRes(res);
          setLoading(false);
        })
        .catch(err => {
          console.error("Research gap fetch error:", err);
          setErrorMsg(err.response?.data?.detail || "Failed to fetch research gaps from backend.");
          setLoading(false);
        });
    }
  }, [activeWorkspace]);

  return (
    <div className="max-w-4xl mx-auto space-y-8">
      {/* Header */}
      <div className="space-y-2">
        <div className="inline-flex items-center space-x-2 px-3 py-1 rounded-full bg-brand-100 dark:bg-brand-950 text-brand-600 dark:text-brand-400 text-xs font-bold uppercase">
          <Sparkles className="w-4 h-4" />
          <span>Backend Research Gap Analysis</span>
        </div>
        <h1 className="text-2xl font-extrabold text-slate-900 dark:text-white">Research Gap Detection</h1>
        <p className="text-xs text-slate-500">Analysis generated by backend Gemini 3.6 Flash from your paper collection.</p>
      </div>

      {loading ? (
        <div className="p-12 text-center text-xs text-slate-400 bg-white dark:bg-slate-900 rounded-3xl border border-slate-200 dark:border-slate-800">
          Analyzing papers and generating research gap analysis via backend...
        </div>
      ) : errorMsg ? (
        <div className="p-6 rounded-3xl bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-800 text-rose-600 dark:text-rose-400 text-xs flex items-center space-x-2">
          <AlertCircle className="w-5 h-5 flex-shrink-0" />
          <span>{errorMsg}</span>
        </div>
      ) : gapRes?.message ? (
        <div className="p-8 rounded-3xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 text-center space-y-3">
          <div className="w-12 h-12 rounded-2xl bg-amber-100 dark:bg-amber-950 text-amber-600 mx-auto flex items-center justify-center">
            <BookOpen className="w-6 h-6" />
          </div>
          <h3 className="text-sm font-bold text-slate-800 dark:text-slate-200">Backend Status Message</h3>
          <p className="text-xs text-slate-500 max-w-md mx-auto">{gapRes.message}</p>
        </div>
      ) : gapRes?.gap_analysis ? (
        <div className="p-8 rounded-3xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xl space-y-6">
          <div className="border-b border-slate-100 dark:border-slate-800 pb-4">
            <span className="text-xs font-bold text-brand-500 uppercase">Analyzed Collection</span>
            <h3 className="text-lg font-bold text-slate-900 dark:text-white mt-1">
              Analysis across {gapRes.papers_analyzed} papers
            </h3>
            {gapRes.paper_titles && (
              <div className="flex flex-wrap gap-1.5 mt-2">
                {gapRes.paper_titles.map((t, i) => (
                  <span key={i} className="px-2.5 py-1 rounded-lg bg-slate-100 dark:bg-slate-800 text-[10px] font-bold text-slate-700 dark:text-slate-300 flex items-center gap-1">
                    <FileText className="w-3 h-3 text-brand-500" /> {t}
                  </span>
                ))}
              </div>
            )}
          </div>

          <div className="prose dark:prose-invert max-w-none text-xs leading-relaxed text-slate-700 dark:text-slate-300 whitespace-pre-wrap font-sans">
            {gapRes.gap_analysis}
          </div>
        </div>
      ) : null}
    </div>
  );
}
